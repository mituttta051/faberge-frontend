/** Зал музея (этаж, помещение). */
export interface Hall {
  id: number;
  /**
   * Номер зала на плане экспозиции. Может отсутствовать: у зала «Вне постоянной
   * экспозиции» номера нет (бэкенд отдаёт `hall_number: null`).
   */
  hallNumber?: number;
  /** Название зала (напр. «Синяя гостиная») */
  name?: string;
  /** Описание зала (для блока «Описание зала» и шапки) */
  description?: string;
  /** Этаж/уровень в здании музея */
  level?: number;
  /** Заглавное фото зала */
  coverImageUrl?: string;
  showcaseCount?: number;
  exhibitCount?: number;
  /** Помечен ли зал как временная выставка (отдельный каталог + бейдж). */
  isTemporary?: boolean;
  /**
   * Служебная запись каталога: в публичной выдаче не появляется, приходит только
   * в админку (`GET /halls?include_service=true`).
   */
  isService?: boolean;
  /**
   * Позиция зала в каталоге (drag-n-drop в админке). Сервер уже отдаёт залы
   * отсортированными по нему, поэтому порядок массива — источник правды;
   * само поле нужно только чтобы показать позицию и отличить «не задан» (0).
   */
  sortOrder?: number;
}
