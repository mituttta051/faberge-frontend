/** Экспонат — основная сущность каталога. */
export interface Exhibit {
  id: number;
  /** Номер экспоната по путеводителю музея (строка: «01», «12а»). Ставится перед названием. */
  exhibitNumber?: string;
  showcaseId?: number;
  /** ID зала. У полной карточки приходит через `hall.id`, у summary — как `hall_id`. */
  hallId?: number;
  /**
   * Номер зала на плане. Пусто — зал «Вне постоянной экспозиции», номера у него нет.
   */
  hallNumber?: number;
  /** Название зала. */
  hallName?: string;
  /**
   * Расположение готовой строкой — «Зал 4 «Синяя гостиная», витрина 5».
   *
   * С 31.08.2026 бэкенд отдаёт её сам (`location.text`) тем же кодом, которым
   * ИИ-гид печатает «Найти его можно в зале 4…»: раньше формулировок было две и
   * они расходились. Пока прод не обновлён, строку собирает `exhibitLocation()`
   * — по тому же формату, чтобы после деплоя текст не поменялся.
   */
  locationText?: string;
  /**
   * Номер витрины в пределах зала. Приходит и у карточки (`showcase.showcase_number`),
   * и в списках (`showcase_number` в summary — с 29.07.2026). Пусто — экспонат
   * стоит вне витрин.
   */
  showcaseNumber?: number;
  /** Slug, который возвращает YOLO. Напр. 'faberge_egg_winter' */
  labelSlug?: string;
  /** Название экспоната */
  name: string;
  /** Датировка строкой, как в путеводителе: «1899–1903», «конец XIX века». До 17.08.2026 — число. */
  yearCreated?: string;
  /**
   * Место создания — вторая половина «даты создания и места» с макета музея
   * (`origin_place`, с 31.08.2026). Показывается рядом с датировкой.
   */
  originPlace?: string;
  /**
   * «Фирма К. Фаберже, мастер М. Перхин» — фирма и мастер одной строкой.
   *
   * В базе они лежат в одном поле, и `maker.text` — дословная его копия, всегда
   * авторитетная. Разобранные `maker.firm`/`maker.master` бэкенд тоже отдаёт, но
   * пока не используем: разделять ли их в интерфейсе — открытый вопрос к музею.
   */
  masterName?: string;
  /** Материалы (горный хрусталь, эмаль и т.п.) */
  material?: string;
  /** Техники исполнения (литье, чеканка и т.п.) — отдельное поле с 13.08.2026. */
  techniques?: string;
  /** Краткое описание для карточки */
  shortDescription?: string;
  /** Главное фото (для карточки — image_url, для summary — thumbnail_url). */
  photoUrl?: string;
  /** Ссылка на 3D-модель Koinovo */
  model3dUrl?: string;
  /** HTML/iframe embed-код 3D-модели */
  model3dEmbed?: string;
  /** Предсинтезированная озвучка краткого описания */
  audioUrl?: string;
  /** Первоисточник описания на сайте музея */
  sourceUrl?: string;
  /** Находится ли экспонат во временной выставке (наследуется от зала). */
  isTemporary?: boolean;
}
